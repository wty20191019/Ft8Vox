     * 去掉 `/` 后缀后按最长前缀匹配；呼号须含数字（否则不像呼号，直接放弃）。
     */
    fun locate(call: String?): Place? {
        val c = call?.trim()?.uppercase()?.substringBefore('/') ?: return null
        if (c.isEmpty() || c.none { it.isDigit() }) return null
        for ((prefix, place) in TABLE) {
            if (c.startsWith(prefix)) return place
        }
        return null
    }
