     * 解析呼号所属实体；无法识别返回 `null`。
     *
     * 去掉 `/` 后缀并按最长前缀匹配；呼号须含数字（否则不像呼号，直接放弃）。
     */
    fun resolve(call: String?): Entity? {
        val c = call?.trim()?.uppercase()?.substringBefore('/') ?: return null
        if (c.isEmpty() || c.none { it.isDigit() }) return null
        for ((prefix, name) in PREFIX) {
            if (c.startsWith(prefix)) return byName[name]
        }
        return null
    }

    /** 自检：返回目标实体名不在 [entities] 中的前缀（应为空；供单测守护表内一致性）。 */
    fun unknownPrefixTargets(): List<String> =
        PREFIX.filterValues { it !in byName }.keys.toList()
